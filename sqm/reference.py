def defect_name(code):
    d = DEFECT_CODES.get(code)
    return d[0] if d else code


def build_alias_map():
    """名称/同义词（小写）-> 标准代码"""
    m = {}
    for code, (name, _cat, _sev, _safe, aliases) in DEFECT_CODES.items():
        m[name.lower()] = code
        m[code.lower()] = code
        for a in aliases:
            m[a.lower()] = code
    return m
